"""
publisher.py — Newsletter generation for AI Pulse
Renders approved articles into a beautiful HTML newsletter and plain Markdown.
"""
import os
from datetime import datetime
from pathlib import Path
from jinja2 import Environment, FileSystemLoader, select_autoescape

from config import OUTPUTS_DIR, TEMPLATE_PATH, CATEGORY_COLORS


# ─── Jinja2 Setup ─────────────────────────────────────────────────────────────

def _get_jinja_env() -> Environment:
    template_dir = str(Path(TEMPLATE_PATH).parent)
    return Environment(
        loader=FileSystemLoader(template_dir),
        autoescape=select_autoescape(["html"]),
    )


# ─── HTML Publisher ───────────────────────────────────────────────────────────

def render_html_newsletter(
    articles: list[dict],
    title: str,
    editor_note: str,
    fmt: str = "weekly",
) -> str:
    """Render approved articles into a full HTML newsletter string."""
    env = _get_jinja_env()
    template = env.get_template(Path(TEMPLATE_PATH).name)

    now = datetime.now()
    date_str = now.strftime("%B %d, %Y")
    week_num = now.isocalendar()[1]

    # Attach colour info to each article for the template
    for a in articles:
        a["category_color"] = CATEGORY_COLORS.get(a.get("category", ""), "#6c63ff")

    html = template.render(
        title=title,
        editor_note=editor_note,
        articles=articles,
        date_str=date_str,
        week_num=week_num,
        fmt=fmt,
        year=now.year,
    )
    return html


# ─── Markdown Publisher ───────────────────────────────────────────────────────

def render_markdown_newsletter(
    articles: list[dict],
    title: str,
    editor_note: str,
    fmt: str = "weekly",
) -> str:
    """Render a plain Markdown version of the newsletter."""
    now = datetime.now()
    date_str = now.strftime("%B %d, %Y")

    lines = [
        f"# {title}",
        f"*{date_str} · {'Weekly' if fmt == 'weekly' else 'Monthly'} Edition*",
        "",
        f"> {editor_note}",
        "",
        "---",
        "",
        "## 🔥 Top Stories",
        "",
    ]

    for i, a in enumerate(articles, 1):
        lines += [
            f"### {i}. {a.get('ai_headline', a.get('title', 'Untitled'))}",
            f"**{a.get('category', '')}** · ⏱ {a.get('reading_time', '?')} min read · Source: [{a.get('source', '')}]({a.get('link', '')})",
            "",
            a.get("ai_summary", ""),
            "",
            f"**💡 Why It Matters:** {a.get('why_it_matters', '')}",
            "",
            f"**⚡ Quick Challenge:** {a.get('quick_challenge', '')}",
            "",
            f"[Read Full Article →]({a.get('link', '')})",
            "",
            "---",
            "",
        ]

    lines += [
        "*This newsletter was generated by AI Pulse · Built with Gemini AI*",
    ]
    return "\n".join(lines)


# ─── Save to Disk ─────────────────────────────────────────────────────────────

def save_newsletter(html: str, md: str, fmt: str = "weekly") -> tuple[str, str]:
    """
    Save HTML and Markdown newsletters to the outputs directory.
    Returns (html_path, md_path).
    """
    Path(OUTPUTS_DIR).mkdir(parents=True, exist_ok=True)
    timestamp = datetime.now().strftime("%Y-%m-%d_%H%M")

    html_path = os.path.join(OUTPUTS_DIR, f"newsletter_{timestamp}.html")
    md_path   = os.path.join(OUTPUTS_DIR, f"newsletter_{timestamp}.md")

    with open(html_path, "w", encoding="utf-8") as f:
        f.write(html)
    with open(md_path, "w", encoding="utf-8") as f:
        f.write(md)

    print(f"[publisher] Saved → {html_path}")
    print(f"[publisher] Saved → {md_path}")
    return html_path, md_path


# ─── Convenience Wrapper ──────────────────────────────────────────────────────

def generate_newsletter(
    articles: list[dict],
    title: str = "AI Pulse",
    editor_note: str = "Here are this week's most important AI updates for CS students.",
    fmt: str = "weekly",
    save: bool = True,
) -> dict:
    """
    Full pipeline: render HTML + Markdown → optionally save → return both.
    """
    html = render_html_newsletter(articles, title, editor_note, fmt)
    md   = render_markdown_newsletter(articles, title, editor_note, fmt)

    html_path = md_path = None
    if save:
        html_path, md_path = save_newsletter(html, md, fmt)

    return {
        "html":      html,
        "markdown":  md,
        "html_path": html_path,
        "md_path":   md_path,
    }
